CREATE TABLE ALUNO (
    ID_Aluno NUMBER(10) NOT NULL,
    Nome_Aluno VARCHAR2(150 CHAR) NOT NULL,
    CONSTRAINT PK_ALUNO PRIMARY KEY (ID_Aluno)
);

CREATE TABLE ALUNO_TELEFONE (
    ID_Aluno NUMBER(10) NOT NULL,
    Telefone VARCHAR2(25 CHAR) NOT NULL,
    CONSTRAINT PK_ALUNO_TELEFONE PRIMARY KEY (ID_Aluno, Telefone)
);

CREATE TABLE MATRICULA (
    ID_Aluno NUMBER(10) NOT NULL,
    Cod_Turma VARCHAR2(20 CHAR) NOT NULL,
    Nota_Final NUMBER(4,2),
    CONSTRAINT PK_MATRICULA PRIMARY KEY (ID_Aluno, Cod_Turma)
);

CREATE TABLE TURMA (
    Cod_Turma VARCHAR2(20 CHAR) NOT NULL,
    Cod_Curso VARCHAR2(20 CHAR) NOT NULL,
    Nome_Curso VARCHAR2(150 CHAR) NOT NULL,
    Carga_Horaria NUMBER(6) NOT NULL,
    ID_Instrutor VARCHAR2(20 CHAR) NOT NULL,
    Nome_Instrutor VARCHAR2(150 CHAR) NOT NULL,
    CONSTRAINT PK_TURMA PRIMARY KEY (Cod_Turma)
);

ALTER TABLE ALUNO_TELEFONE ADD CONSTRAINT FK_ALUNO_TELEFONE_ALUNO
    FOREIGN KEY (ID_Aluno) REFERENCES ALUNO (ID_Aluno);

ALTER TABLE MATRICULA ADD CONSTRAINT FK_MATRICULA_ALUNO
    FOREIGN KEY (ID_Aluno) REFERENCES ALUNO (ID_Aluno);

ALTER TABLE MATRICULA ADD CONSTRAINT FK_MATRICULA_TURMA
    FOREIGN KEY (Cod_Turma) REFERENCES TURMA (Cod_Turma);
